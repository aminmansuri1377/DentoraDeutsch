export function modelGroup(name: string) {
  if (
    [
      "Specialty",
      "Course",
      "Chapter",
      "Lesson",
      "LessonBlock",
      "Question",
      "AnswerOption",
    ].includes(name)
  )
    return "Lerninhalte";
  if (["User", "Account", "Session", "VerificationToken"].includes(name))
    return "Mitglieder & Zugang";
  if (
    [
      "Post",
      "Media",
      "Comment",
      "PostLike",
      "PostBookmark",
      "Follow",
      "Report",
    ].includes(name)
  )
    return "Community";
  if (
    [
      "Product",
      "Order",
      "Entitlement",
      "WebhookEvent",
      "Coupon",
      "CouponRedemption",
      "StudentVerification",
    ].includes(name)
  )
    return "Shop & Bestellungen";
  if (
    [
      "Ticket",
      "TicketMessage",
      "Feedback",
      "Notification",
      "AuditLog",
      "RateLimit",
    ].includes(name)
  )
    return "Service & System";
  return "Lernen & Fortschritt";
}
